// Builds the single-file CLI bundle that the Claude Code plugin ships.
//
// A marketplace install copies only the plugin directory, so the CLI cannot depend on this repository's
// sibling packages or node_modules. This bundles the CLI, the engine, the analyzer, the JSON schemas
// and ajv into plugins/engineering-governance/bundle/governance.mjs.
//
// Usage: node scripts/bundle-plugin.mjs [--out <file>]
// With --out only the bundle is written (used by the staleness test); without it the plugin's bundle,
// starter templates, third-party notices and licence copy are refreshed.

import { build } from "esbuild";
import { copyFile, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const cliDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = path.resolve(cliDirectory, "../..");
const pluginDirectory = path.join(repositoryRoot, "plugins", "engineering-governance");

const outIndex = process.argv.indexOf("--out");
const customOut = outIndex >= 0 ? process.argv[outIndex + 1] : undefined;
if (outIndex >= 0 && !customOut) throw new Error("--out requires a file path.");
const outfile = customOut ? path.resolve(customOut) : path.join(pluginDirectory, "bundle", "governance.mjs");

// config.ts loads ajv through `createRequire(import.meta.url)`, which a bundler cannot follow. Removing
// that shim at build time turns `require("ajv/...")` into a plain require the bundler inlines. The
// source is left untouched. If the source changes shape this fails loudly instead of shipping a
// bundle that cannot find ajv.
const REQUIRE_IMPORT = 'import { createRequire } from "node:module";';
const REQUIRE_SHIM = "const require = createRequire(import.meta.url);";

const inlineAjv = {
  name: "inline-ajv",
  setup(builder) {
    builder.onLoad({ filter: /[\\/]cli[\\/]src[\\/]config\.ts$/ }, async ({ path: file }) => {
      const source = await readFile(file, "utf8");
      if (!source.includes(REQUIRE_IMPORT) || !source.includes(REQUIRE_SHIM)) {
        throw new Error("cli/src/config.ts no longer loads ajv through createRequire; update scripts/bundle-plugin.mjs.");
      }
      return { contents: source.replace(REQUIRE_IMPORT, "").replace(REQUIRE_SHIM, ""), loader: "ts" };
    });
  },
};

const result = await build({
  absWorkingDir: cliDirectory,
  entryPoints: ["src/index.ts"],
  outfile,
  bundle: true,
  platform: "node",
  target: "node22",
  format: "esm",
  legalComments: "none",
  logLevel: "warning",
  metafile: true,
  plugins: [inlineAjv],
});

// The bundle inlines third-party packages, and their licenses require the notice to travel with the
// code. esbuild strips comments, so the notices are generated from each package's own license file.
// A bundled package without a license file fails the build rather than shipping unattributed.
async function thirdPartyNotices() {
  const packages = new Map();
  for (const input of Object.keys(result.metafile.inputs)) {
    const parts = input.replaceAll("\\", "/").split("/");
    const index = parts.lastIndexOf("node_modules");
    if (index < 0) continue;
    const name = parts[index + 1]?.startsWith("@") ? `${parts[index + 1]}/${parts[index + 2]}` : parts[index + 1];
    const directory = path.resolve(cliDirectory, ...parts.slice(0, index + 1), ...name.split("/"));
    packages.set(name, directory);
  }

  const sections = [];
  for (const [name, directory] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
    const manifest = JSON.parse(await readFile(path.join(directory, "package.json"), "utf8"));
    const licenseFile = (await readdir(directory)).find((file) => /^(licen[cs]e|copying)(\.[a-z]+)?$/i.test(file));
    if (!licenseFile) throw new Error(`Bundled package ${name} has no license file; add its notice before shipping.`);
    const text = (await readFile(path.join(directory, licenseFile), "utf8")).replaceAll("\r\n", "\n").trim();
    sections.push(`## ${name} ${manifest.version} (${manifest.license ?? "see license text"})\n\n${text}\n`);
  }
  return [
    "# Third-party notices",
    "",
    "The bundled command-line tool (`bundle/governance.mjs`) includes the packages below. Each is distributed",
    "under its own license, reproduced here. This file is generated by `npm run bundle:plugin`; do not edit it.",
    "",
    ...sections,
  ].join("\n");
}

if (!customOut) {
  await writeFile(path.join(pluginDirectory, "THIRD-PARTY-NOTICES.md"), await thirdPartyNotices());
  // A marketplace install copies only the plugin directory, so the license must be inside it.
  await copyFile(path.join(repositoryRoot, "LICENSE"), path.join(pluginDirectory, "LICENSE"));
  // Starter files users copy into their own repository. The source of truth stays in model/.
  const templates = path.join(pluginDirectory, "templates");
  await mkdir(templates, { recursive: true });
  await copyFile(
    path.join(repositoryRoot, "22-governance-operations", "model", "example-governance-pack.json"),
    path.join(templates, "governance-pack.example.json"),
  );
  await copyFile(
    path.join(repositoryRoot, "22-governance-operations", "model", "architecture-profile-clean-architecture.json"),
    path.join(templates, "architecture-profile-clean-architecture.json"),
  );

  // The review command cites the standards, so the ones its areas use ship inside the plugin. The
  // source of truth stays in the repository; a test checks the copies are identical.
  const index = JSON.parse(await readFile(path.join(templates, "standards-index.json"), "utf8"));
  const areas = JSON.parse(await readFile(path.join(templates, "review-areas.json"), "utf8"));
  const ids = new Set([
    ...areas.common_standards,
    ...Object.values(areas.areas).flatMap((area) => area.standards),
  ]);
  const standards = path.join(pluginDirectory, "standards");
  await mkdir(standards, { recursive: true });
  for (const id of [...ids].sort()) {
    const entry = index.standards.find((standard) => standard.id === id);
    if (!entry) throw new Error(`review-areas.json names ${id}, which is not in standards-index.json.`);
    await copyFile(path.join(repositoryRoot, entry.file), path.join(standards, path.basename(entry.file)));
  }
}

console.log(`Wrote ${path.relative(repositoryRoot, outfile)}`);
